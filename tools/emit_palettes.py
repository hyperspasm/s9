#!/usr/bin/env python3
"""Emit src/palette.h: the spectrogram's color scales as tables of 256 RGB bytes, dark to
bright, with the enum and the names that choose between them.

    python3 tools/emit_palettes.py

The scales are fetched from their projects' repositories at fixed releases, tables computed
in a perceptual color model so that equal steps in level look like equal steps in
brightness. Inferno, magma, plasma and viridis are matplotlib's, created by Nathaniel J.
Smith and Stéfan van der Walt, with Eric Firing for viridis, and released into the public
domain under the CC0 dedication. Mako and rocket are seaborn's, Copyright (c) 2012-2023
Michael L. Waskom, under the BSD 3-clause license. Turbo is Google's, by Anton Mikhailov,
under the Apache 2.0 license, taken from matplotlib's copy. Grey is a straight ramp; heat
runs from black through red and yellow to white. Needs nothing but the standard library
and the network.
"""
import ast
import os
import urllib.request

# a source file, the name a table has in it, and the tables taken from it
SOURCES = [
    ("https://raw.githubusercontent.com/matplotlib/matplotlib/v3.9.0/lib/matplotlib/_cm_listed.py", "_{}_data",
     ["inferno", "magma", "plasma", "viridis", "turbo"]),
    ("https://raw.githubusercontent.com/mwaskom/seaborn/v0.13.2/seaborn/cm.py", "_{}_lut",
     ["mako", "rocket"]),
]
ORDER = ["inferno", "magma", "plasma", "viridis", "mako", "rocket", "turbo"]   # the fetched scales, then the ramps
STEPS = 256
PER_LINE = 6


def fetch_tables(url, pattern, names):
    """The named color maps of a source file, each 256 (r, g, b) triples in 0..1."""
    wanted = {pattern.format(name): name for name in names}
    src = urllib.request.urlopen(url, timeout=60).read().decode()
    tables = {}
    for node in ast.parse(src).body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            name = wanted.get(node.targets[0].id)
            if name:
                tables[name] = ast.literal_eval(node.value)
    missing = set(names) - set(tables)
    assert not missing, f"{url}: {missing}"
    return tables


def ramp(stops):
    """STEPS colors interpolated between (position, (r, g, b)) stops in 0..1."""
    out = []
    for i in range(STEPS):
        u = i / (STEPS - 1)
        for (u0, c0), (u1, c1) in zip(stops, stops[1:]):
            if u0 <= u <= u1:
                t = (u - u0) / (u1 - u0)
                out.append(tuple(c0[k] + t * (c1[k] - c0[k]) for k in range(3)))
                break
    return out


def to_bytes(table):
    return [tuple(int(v * 255.0 + 0.5) for v in rgb) for rgb in table]


def main():
    fetched = {}
    for url, pattern, names in SOURCES:
        fetched.update(fetch_tables(url, pattern, names))
    palettes = [(name, to_bytes(fetched[name])) for name in ORDER]
    palettes.append(("grey", [(i, i, i) for i in range(STEPS)]))
    palettes.append(("heat", to_bytes(ramp([(0.0, (0, 0, 0)), (1 / 3, (1, 0, 0)), (2 / 3, (1, 1, 0)), (1.0, (1, 1, 1))]))))
    for name, table in palettes:
        assert len(table) == STEPS, name

    lines = [
        "/* Generated by tools/emit_palettes.py; do not edit by hand.",
        " * The spectrogram's color scales: 256 RGB bytes each, dark to bright. Inferno,",
        " * magma, plasma and viridis are matplotlib's, public domain under CC0. Mako and",
        " * rocket are seaborn's, Copyright (c) 2012-2023 Michael L. Waskom, BSD 3-clause.",
        " * Turbo is Google's, Apache 2.0. Grey and heat are ramps. */",
        "#ifndef palette_h",
        "#define palette_h",
        "",
        "#include <stdint.h>",
        "",
        "typedef enum {",
    ]
    lines += [f"\tPALETTE_{name.upper()}," for name, _ in palettes]
    lines += ["\tPALETTE_COUNT,", "} palette_t;", "", "static const char *const palette_names[PALETTE_COUNT] = {"]
    lines += [f'\t[PALETTE_{name.upper()}] = "{name}",' for name, _ in palettes]
    lines += ["};", "", "#define PALETTE_STEPS %d" % STEPS, "", "static const uint8_t palette_tables[PALETTE_COUNT][PALETTE_STEPS][3] = {"]
    for name, table in palettes:
        lines.append(f"\t[PALETTE_{name.upper()}] = {{")
        for i in range(0, STEPS, PER_LINE):
            lines.append("\t\t" + " ".join("{ %3d, %3d, %3d }," % rgb for rgb in table[i:i + PER_LINE]))
        lines.append("\t},")
    lines += ["};", "", "#endif /* palette_h */", ""]

    out = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", "src", "palette.h"))
    with open(out, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {out}: {', '.join(name for name, _ in palettes)}")


if __name__ == "__main__":
    main()
