"""Helpers for writing golden tables as C headers."""
import os


def repo_path(*parts):
    return os.path.normpath(os.path.join(os.path.dirname(__file__), "..", "..", *parts))


def c_double(v):
    return "%.17g" % float(v)


def c_array(name, values, per_line=4, ctype="double"):
    lines = [f"static const {ctype} {name}[{len(values)}] = {{"]
    for i in range(0, len(values), per_line):
        chunk = ", ".join(c_double(v) if ctype == "double" else str(v) for v in values[i:i + per_line])
        lines.append(f"\t{chunk},")
    lines.append("};")
    return "\n".join(lines)


def c_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def header(guard, script, what, body):
    return "\n".join([
        f"/* Generated by s9 validation (scripts/{script}); do not edit by hand.",
        f" * {what} */",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        body,
        "",
        f"#endif /* {guard} */",
        "",
    ])
